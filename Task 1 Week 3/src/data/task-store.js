// Read-only data access for tasks (Stage 1).
// Every query is parameterized (? placeholders): user-supplied values are
// bound separately from the SQL text, so a malicious value like
// "1 OR 1 = 1" is treated as literal data and can never change the query's
// meaning. This is our defense against SQL injection.

const db = require("./db");

// Convert a raw database row into the API shape.
//
// SQLite has no real boolean type, so "done" is stored as 0/1. The Week 2
// in-memory API returned true/false, so we map it back here to keep the JSON
// responses byte-for-byte identical to the original version.
function mapRowToTask(row) {
  return {
    id: row.id,
    title: row.title,
    done: row.done === 1,
  };
}

// Return every task, oldest first (matching the in-memory array order).
function getAllTasks() {
  const rows = db.prepare("SELECT * FROM tasks ORDER BY id").all();

  return rows.map(mapRowToTask);
}

// Find a single task by its numeric id.
// Returns the task object, or null if no task with that id exists.
function findTaskById(id) {
  const row = db.prepare("SELECT * FROM tasks WHERE id = ?").get(id);

  // better-sqlite3 returns undefined when no row matches; the route layer
  // expects null (same contract as the in-memory store), so we normalize.
  return row === undefined ? null : mapRowToTask(row);
}

// Create a new task with the given title.
// The id is generated by SQLite (AUTOINCREMENT), so callers cannot inject
// their own ids, and every new task starts as "not done" - same behavior
// as the in-memory version.
function createTask(title) {
  const result = db
    .prepare("INSERT INTO tasks (title, done) VALUES (?, ?)")
    .run(title, 0);

  // lastInsertRowid holds the id SQLite just assigned to our new row,
  // so we can return the full task object exactly like the old store did.
  return {
    id: Number(result.lastInsertRowid),
    title: title,
    done: false,
  };
}

// Update an existing task with the given fields (title and/or done).
// Returns the updated task object, or null if no task has that id.
//
// Why build the SET clause dynamically instead of writing every column
// unconditionally? A PUT may update only one field, and blindly overwriting
// both columns would wipe out data the client did not send. Only the fields
// that passed route validation end up in the query - always as bound ? values,
// never string-concatenated, so injection is still impossible.
function updateTask(id, updatedFields) {
  // Map each allowed field to its assignment fragment, e.g. "title = ?".
  const setClauses = [];
  const values = [];

  if (updatedFields.title !== undefined) {
    setClauses.push("title = ?");
    values.push(updatedFields.title);
  }

  if (updatedFields.done !== undefined) {
    setClauses.push("done = ?");
    // Convert the API's true/false back to SQLite's 1/0 for storage.
    values.push(updatedFields.done ? 1 : 0);
  }

  // Attach the id as the final parameter for the WHERE clause.
  values.push(id);

  const result = db
    .prepare(`UPDATE tasks SET ${setClauses.join(", ")} WHERE id = ?`)
    .run(...values);

  // changes tells us how many rows the UPDATE actually touched:
  // 0 means no task with this id existed -> report null (the route turns
  // that into a 404), exactly like the in-memory version.
  if (result.changes === 0) {
    return null;
  }

  return findTaskById(id);
}

// Remove a task from the database by id.
// Returns true if a row was removed, or false if no task had that id.
function deleteTask(id) {
  const result = db.prepare("DELETE FROM tasks WHERE id = ?").run(id);

  return result.changes > 0;
}

module.exports = {
  getAllTasks,
  findTaskById,
  createTask,
  updateTask,
  deleteTask,
};
